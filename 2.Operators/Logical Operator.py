
a = 10
b = 20

print("Values:")
print("a =", a)
print("b =", b)

# AND Operator
print("\nLogical AND")
print("(a < b) and (a > 5) =", (a < b) and (a > 5))
print("(a > b) and (a > 5) =", (a > b) and (a > 5))

# OR Operator
print("\nLogical OR")
print("(a < b) or (a > 20) =", (a < b) or (a > 20))
print("(a > b) or (a > 20) =", (a > b) or (a > 20))

# NOT Operator
print("\nLogical NOT")
print("not(a < b) =", not(a < b))
print("not(a > b) =", not(a > b))